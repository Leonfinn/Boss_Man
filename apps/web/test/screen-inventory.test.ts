// Screen inventory (BOS-1054): a committed list, per route and Settings panel, of its section headings and the API paths
// it reads, read from the source with no browser (screen-scan.ts). A change that drops a section or an API read changes
// the list, so the diff in screen-inventory.txt shows it to the reviewer. After a change you meant, refresh the list:
//   pnpm --filter @boss-man/web exec vitest run test/screen-inventory.test.ts -u
// Redirects (an old address that now opens another page) must keep what the old page showed, or say it was removed on purpose.
import { describe, expect, it } from "vitest";
import { allScreens, inventoryOf, type Inventory } from "./screen-scan";

type Keep = { sections?: string[]; reads?: string[] };
type Redirect = {
  from: string;
  to: string;
  /** What the old page showed that the new one must still show. */
  keeps: Keep;
  /** What the old page showed that is not on the target on purpose: where it went or why it is gone. */
  removedOnPurpose?: Array<{ what: string; why: string }>;
};

// The redirects in settingsRedirect (pages/Settings.tsx). Add a line here when you add a redirect there.
const REDIRECTS: Redirect[] = [
  { from: "#/funding", to: "#/settings/<company>/funding", keeps: { sections: ["Funding sources", "Budgets"], reads: ["/api/funding-sources", "/api/funding-sources/:id/status", "/api/budgets"] } },
  { from: "#/secrets", to: "#/settings/<company>/secrets", keeps: { sections: ["All stored secrets"], reads: ["/api/secrets"] } },
  { from: "#/rules", to: "#/settings/<company>/permissions", keeps: { sections: ["Try a command"], reads: ["/api/policy-rules"] } },
  {
    from: "#/settings/<company>/access",
    to: "#/settings/<company>/tools",
    keeps: { sections: ["Tool servers (MCP)", "Deploy targets"] },
    removedOnPurpose: [
      { what: "Funding sources", why: "BOS-1018 moved it to the Funding page" },
      { what: "Credentials", why: "BOS-1018 moved it to the Secrets page" },
    ],
  },
  {
    from: "#/notifications/<anything>",
    to: "#/settings/<company>/notifications",
    keeps: { sections: ["How you're told", "Set up your phone", "Other places to send alerts", "Weekly summary"], reads: ["/api/notification-settings", "/api/alert-destinations", "/api/notifications/pushes"] },
  },
  {
    from: "#/settings/<company>/workflow",
    to: "#/settings/<company>/reviews",
    keeps: { sections: ["Reviews", "Did it move the goal?"] },
    removedOnPurpose: [{ what: "CEO chapters", why: "BOS-1018 moved it to Team and CEO" }],
  },
];

const byId = (inv: Inventory[]) => new Map(inv.map((i) => [i.id, i]));

function render(inv: Inventory[]): string {
  const lines = [
    "# Screen inventory (BOS-1054). Generated by apps/web/test/screen-inventory.test.ts; refresh with vitest -u.",
    "# Per route and Settings panel: the section headings it shows and the /api paths it reads (GET). A dropped line here is a dropped section or read.",
    "",
  ];
  for (const i of inv) {
    lines.push(`## ${i.id}`);
    lines.push(`sections: ${i.sections.length ? "" : "(none)"}`);
    for (const s of i.sections) lines.push(`  - ${s}`);
    lines.push(`reads: ${i.reads.length ? "" : "(none)"}`);
    for (const r of i.reads) lines.push(`  - ${r}`);
    lines.push("");
  }
  lines.push("## Redirects");
  for (const r of REDIRECTS) {
    lines.push(`${r.from} -> ${r.to}`);
    for (const s of r.keeps.sections ?? []) lines.push(`  keeps section: ${s}`);
    for (const a of r.keeps.reads ?? []) lines.push(`  keeps read: ${a}`);
    for (const x of r.removedOnPurpose ?? []) lines.push(`  removed on purpose: ${x.what} (${x.why})`);
  }
  return lines.join("\n") + "\n";
}

describe("screen inventory", () => {
  const inv = allScreens()
    .map(inventoryOf)
    .sort((a, b) => a.id.localeCompare(b.id));

  it("matches the committed list (screen-inventory.txt)", async () => {
    await expect(render(inv)).toMatchFileSnapshot("./screen-inventory.txt");
  });

  it("covers every route App.tsx has and every Settings panel", () => {
    const ids = inv.map((i) => i.id);
    for (const want of ["#/board", "#/settings", "#/settings/<company>/funding", "#/settings/<company>/secrets", "#/settings/<company>/permissions", "#/(default)"]) expect(ids).toContain(want);
    // A screen that reads as empty is a scanner miss, not a quiet page.
    const bare = inv.filter((i) => !i.sections.length && !i.reads.length).map((i) => i.id);
    expect(bare, "These screens read as having no sections and no API reads: the scan lost them").toEqual([]);
  });

  it("keeps what each redirect's old page showed (or names it as removed on purpose)", () => {
    const map = byId(inv);
    for (const r of REDIRECTS) {
      const target = map.get(r.to);
      expect(target, `${r.from} redirects to ${r.to}, which is not a screen`).toBeDefined();
      for (const s of r.keeps.sections ?? []) expect(target!.sections, `${r.to} lost the "${s}" section that ${r.from} showed`).toContain(s);
      for (const a of r.keeps.reads ?? []) expect(target!.reads, `${r.to} lost the ${a} read that ${r.from} made`).toContain(a);
      for (const x of r.removedOnPurpose ?? []) expect(x.why.trim(), `${r.from}: ${x.what} needs a reason`).not.toBe("");
    }
  });

  it("has a line here for every redirect in settingsRedirect", async () => {
    const { settingsRedirect } = await import("../src/pages/Settings");
    const route = (h: string) => h.split("/");
    const live = (hash: string) => settingsRedirect(route(hash), "c1");
    // Each old address settingsRedirect still sends somewhere must be in REDIRECTS (matched by where it lands).
    const lands = new Set(REDIRECTS.map((r) => r.to.replace("<company>", "c1").replace(/^#\//, "")));
    for (const old of ["funding", "secrets", "rules", "settings/c1/access", "settings/c1/workflow"]) {
      const to = live(old);
      expect(to, `${old} no longer redirects: remove it from REDIRECTS if that is on purpose`).not.toBeNull();
      expect(lands.has(to!), `${old} redirects to ${to}, which REDIRECTS does not list`).toBe(true);
    }
  });
});
